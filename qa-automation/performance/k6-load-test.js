import http from 'k6/http';
import { check, sleep } from 'k6';
import { Rate, Trend } from 'k6/metrics';

// Custom metrics
const errorRate = new Rate('errors');
const responseTime = new Trend('response_time');

// Test configuration
export const options = {
  stages: [
    { duration: '30s', target: 20 },   // Ramp up to 20 users
    { duration: '1m', target: 20 },     // Stay at 20 users
    { duration: '30s', target: 50 },    // Ramp up to 50 users
    { duration: '1m', target: 50 },    // Stay at 50 users
    { duration: '30s', target: 100 },   // Ramp up to 100 users
    { duration: '1m', target: 100 },    // Stay at 100 users
    { duration: '30s', target: 0 },     // Ramp down to 0 users
  ],
  thresholds: {
    http_req_duration: ['p(95)<2000'], // 95% of requests should be below 2s
    http_req_failed: ['rate<0.01'],     // Error rate should be less than 1%
    errors: ['rate<0.01'],
  },
};

const BASE_URL = __ENV.BASE_URL || 'http://localhost:5001';

// Test scenarios
export default function () {
  // Test 1: Health check
  let response = http.get(`${BASE_URL}/api/health`);
  check(response, {
    'health check status is 200': (r) => r.status === 200,
    'health check response time < 500ms': (r) => r.timings.duration < 500,
  }) || errorRate.add(1);
  responseTime.add(response.timings.duration);
  sleep(1);

  // Test 2: Get products
  response = http.get(`${BASE_URL}/api/products`);
  check(response, {
    'products status is 200': (r) => r.status === 200,
    'products response time < 1000ms': (r) => r.timings.duration < 1000,
    'products has data': (r) => JSON.parse(r.body).length > 0,
  }) || errorRate.add(1);
  responseTime.add(response.timings.duration);
  sleep(1);

  // Test 3: Get tasks (if authenticated)
  const authHeaders = {
    headers: {
      'Authorization': `Bearer ${__ENV.AUTH_TOKEN || ''}`,
    },
  };
  
  if (__ENV.AUTH_TOKEN) {
    response = http.get(`${BASE_URL}/api/tasks`, authHeaders);
    check(response, {
      'tasks status is 200': (r) => r.status === 200,
      'tasks response time < 1500ms': (r) => r.timings.duration < 1500,
    }) || errorRate.add(1);
    responseTime.add(response.timings.duration);
    sleep(1);
  }

  // Test 4: Create task (if authenticated)
  if (__ENV.AUTH_TOKEN) {
    const payload = JSON.stringify({
      title: `Load Test Task ${Date.now()}`,
      description: 'Generated by k6 load test',
      status: 'todo',
      priority: 'medium',
    });
    
    response = http.post(`${BASE_URL}/api/tasks`, payload, {
      ...authHeaders,
      headers: {
        ...authHeaders.headers,
        'Content-Type': 'application/json',
      },
    });
    
    check(response, {
      'create task status is 201': (r) => r.status === 201,
      'create task response time < 2000ms': (r) => r.timings.duration < 2000,
    }) || errorRate.add(1);
    responseTime.add(response.timings.duration);
    sleep(1);
  }
}

export function handleSummary(data) {
  return {
    'k6-results.json': JSON.stringify(data),
    'stdout': textSummary(data, { indent: ' ', enableColors: true }),
  };
}

function textSummary(data, options) {
  const indent = options.indent || '  ';
  const enableColors = options.enableColors || false;
  
  let summary = '\n';
  summary += `${indent}✓ Load Test Summary\n`;
  summary += `${indent}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━\n`;
  summary += `${indent}Duration: ${data.state.testRunDurationMs / 1000}s\n`;
  summary += `${indent}VUs: ${data.metrics.vus.values.max}\n`;
  summary += `${indent}Requests: ${data.metrics.http_reqs.values.count}\n`;
  summary += `${indent}Failed: ${data.metrics.http_req_failed.values.rate * 100}%\n`;
  summary += `${indent}Avg Response Time: ${data.metrics.http_req_duration.values.avg.toFixed(2)}ms\n`;
  summary += `${indent}P95 Response Time: ${data.metrics.http_req_duration.values['p(95)'].toFixed(2)}ms\n`;
  summary += `${indent}P99 Response Time: ${data.metrics.http_req_duration.values['p(99)'].toFixed(2)}ms\n`;
  
  return summary;
}
